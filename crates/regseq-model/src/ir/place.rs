//! Place and Projection types for the Regseq Model IR.
//!
//! A [`Place`] represents a memory location: a local variable plus an
//! optional chain of [`Projection`] steps (dereference, field access,
//! indexing, etc.). Places appear on both sides of assignments -- as
//! read sources (inside operands) and as write targets.

use crate::identity::{LocalId, Symbol};
use crate::ir::types::RegseqType;

/// A memory location: a local variable plus an optional chain of projections.
///
/// Maps directly from MIR's `Place<'tcx>`. The projection list is owned
/// (not arena-interned) since the Regseq IR uses owned types throughout.
///
/// An empty projection `Vec` means the place is just the local itself.
#[derive(Clone, Eq, PartialEq, Hash, Debug)]
pub struct Place {
    /// The base local variable.
    pub local: LocalId,
    /// Zero or more projections applied to the local.
    pub projection: Vec<Projection>,
}

/// A single projection step applied to a place.
#[derive(Clone, Eq, PartialEq, Hash, Debug)]
pub enum Projection {
    /// Dereference a pointer or reference.
    ///
    /// Loads the pointer value from the parent place and dereferences it.
    /// Only valid when the parent place is a reference, raw pointer, or Box.
    Deref,

    /// Access a field of a struct, tuple, or enum variant.
    ///
    /// Carries the field index, the field's name (when available), and the
    /// field's type. The name and type are provided directly so consumers
    /// (backends, diagnostics) don't need a lookup.
    ///
    /// `name` is `None` for tuple struct fields (positional) and
    /// compiler-generated fields.
    Field {
        /// Zero-based field index.
        index: u32,
        /// Field name, if it has one (named struct fields).
        name: Option<Symbol>,
        /// The type of this field.
        ty: RegseqType,
    },

    /// Runtime index into an array or slice.
    ///
    /// The index local must have type `usize`.
    Index(LocalId),

    /// Compile-time index generated by array/slice patterns.
    ///
    /// `from_end: false`: `offset` is 0-based from the start.
    /// `from_end: true`: `offset` is 1-based from the end.
    /// `min_length`: the array/slice must be at least this long.
    ConstantIndex {
        /// Offset into the array/slice.
        offset: u64,
        /// Minimum required length of the array/slice.
        min_length: u64,
        /// Whether `offset` counts from the end.
        from_end: bool,
    },

    /// Slice subrange generated by slice patterns.
    ///
    /// `from_end: false`: `array[from..to]`.
    /// `from_end: true`: `slice[from..slice.len() - to]`.
    Subslice {
        /// Start index.
        from: u64,
        /// End index (or offset from end).
        to: u64,
        /// Whether `to` counts from the end.
        from_end: bool,
    },

    /// Select an enum variant before accessing its fields.
    ///
    /// Must precede any `Field` projection on an enum-typed place.
    Downcast {
        /// Variant name (for diagnostics and display).
        name: Option<Symbol>,
        /// Position of the variant in the enum definition.
        variant_index: u32,
    },
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::identity::SymbolInterner;
    use crate::ir::types::ScalarType;

    // -- Construction: bare local place --

    #[test]
    fn construct_bare_local_place() {
        let place = Place {
            local: LocalId(0),
            projection: vec![],
        };
        assert_eq!(place.local, LocalId(0));
        assert!(place.projection.is_empty());
    }

    // -- Construction: field access through deref --

    #[test]
    fn construct_field_access_through_deref() {
        let mut interner = SymbolInterner::new();
        let sym = interner.intern("uart_clk");

        let place = Place {
            local: LocalId(1),
            projection: vec![
                Projection::Deref,
                Projection::Field {
                    index: 0,
                    name: Some(sym),
                    ty: RegseqType::Scalar(ScalarType::U32),
                },
            ],
        };
        assert_eq!(place.local, LocalId(1));
        assert_eq!(place.projection.len(), 2);
    }

    // -- Construction: each of the 6 Projection variants --

    #[test]
    fn construct_projection_deref() {
        let _ = Projection::Deref;
    }

    #[test]
    fn construct_projection_field() {
        let mut interner = SymbolInterner::new();
        let sym = interner.intern("data");
        let _ = Projection::Field {
            index: 3,
            name: Some(sym),
            ty: RegseqType::Bool,
        };
    }

    #[test]
    fn construct_projection_field_no_name() {
        let _ = Projection::Field {
            index: 0,
            name: None,
            ty: RegseqType::Scalar(ScalarType::U8),
        };
    }

    #[test]
    fn construct_projection_index() {
        let _ = Projection::Index(LocalId(5));
    }

    #[test]
    fn construct_projection_constant_index() {
        let _ = Projection::ConstantIndex {
            offset: 2,
            min_length: 4,
            from_end: false,
        };
    }

    #[test]
    fn construct_projection_subslice() {
        let _ = Projection::Subslice {
            from: 1,
            to: 3,
            from_end: true,
        };
    }

    #[test]
    fn construct_projection_downcast() {
        let mut interner = SymbolInterner::new();
        let sym = interner.intern("Some");
        let _ = Projection::Downcast {
            name: Some(sym),
            variant_index: 0,
        };
    }

    #[test]
    fn construct_projection_downcast_no_name() {
        let _ = Projection::Downcast {
            name: None,
            variant_index: 1,
        };
    }

    // -- Equality --

    #[test]
    fn identical_places_are_equal() {
        let a = Place {
            local: LocalId(3),
            projection: vec![Projection::Deref],
        };
        let b = Place {
            local: LocalId(3),
            projection: vec![Projection::Deref],
        };
        assert_eq!(a, b);
    }

    #[test]
    fn different_local_makes_places_unequal() {
        let a = Place {
            local: LocalId(0),
            projection: vec![],
        };
        let b = Place {
            local: LocalId(1),
            projection: vec![],
        };
        assert_ne!(a, b);
    }

    #[test]
    fn different_projection_makes_places_unequal() {
        let a = Place {
            local: LocalId(1),
            projection: vec![Projection::Deref],
        };
        let b = Place {
            local: LocalId(1),
            projection: vec![Projection::Index(LocalId(0))],
        };
        assert_ne!(a, b);
    }

    #[test]
    fn extra_projection_makes_places_unequal() {
        let a = Place {
            local: LocalId(1),
            projection: vec![Projection::Deref],
        };
        let b = Place {
            local: LocalId(1),
            projection: vec![
                Projection::Deref,
                Projection::Field {
                    index: 0,
                    name: None,
                    ty: RegseqType::Scalar(ScalarType::U32),
                },
            ],
        };
        assert_ne!(a, b);
    }

    #[test]
    fn identical_complex_places_are_equal() {
        let mut interner = SymbolInterner::new();
        let sym = interner.intern("status");

        let make_place = || Place {
            local: LocalId(2),
            projection: vec![
                Projection::Deref,
                Projection::Downcast {
                    name: Some(sym),
                    variant_index: 1,
                },
                Projection::Field {
                    index: 0,
                    name: None,
                    ty: RegseqType::Scalar(ScalarType::U32),
                },
            ],
        };
        assert_eq!(make_place(), make_place());
    }
}
