//! MIR place data shapes.
//!
//! Type-narrowing rules from spec.md section 19.4:
//!
//! | Variant | Predecessor `Ty` requirement | Successor `Ty` | Active variant after step |
//! |---|---|---|---|
//! | `Deref` | `Ty::Ref(inner, _)` or `Ty::Ptr(inner, _)` (raw pointer) | the resolved `inner` | `None` (I-Deref-first means no prior `Downcast`) |
//! | `Field(idx, fty)` | when active variant is `None`: `Ty::Struct{..}`, `Ty::Union{..}`, `Ty::Tuple{..}`, or `Ty::Closure(..)` (closure-as-struct shape; see `discussions.md` D6.3 for rationale); when active variant is `Some(v)`: `Ty::Enum{..}` (projecting into variant `v`'s fields) | `fty` (must equal the field type at `idx` in the appropriate variant's field table) | `None` (cleared) |
//! | `Index(_)` | `Ty::Array(elem, _)` or `Ty::Slice(elem)` | the resolved `elem` | unchanged |
//! | `ConstantIndex { from_end: false, ... }` | `Ty::Array(elem, _)` or `Ty::Slice(elem)` | the resolved `elem` | unchanged |
//! | `ConstantIndex { from_end: true, ... }` | `Ty::Slice(elem)` | the resolved `elem` | unchanged |
//! | `Subslice { from, to, from_end: false }` | `Ty::Array(elem, _)` | `Ty::Array(elem, to - from)` | unchanged |
//! | `Subslice { from, to, from_end: true }` | `Ty::Slice(elem)` | `Ty::Slice(elem)` (unchanged) | unchanged |
//! | `Downcast(idx)` | `Ty::Enum{..}` | unchanged | `Some(idx)` |
//!
//! This module records only the data vocabulary. The projection walk
//! that enforces the narrowing rules is P1a-VAL-01
//! (regseq-model-83).

use serde::{Deserialize, Serialize};

use crate::ids::{FieldIdx, LocalId, TyId, VariantIdx};

/// A typed lvalue: head local plus a chain of projections.
///
/// `Place` is body-local content: it appears inside a body's
/// statements / terminators, not in any top-level interner table.
/// Equality is structural over `(local, projection)`.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct Place {
    /// The head local. Must resolve to a `LocalDecl` entry in the
    /// enclosing body's `local_decls` table.
    pub local: LocalId,

    /// The projection chain, applied left-to-right. Empty for a bare
    /// local. Owned slab with no top-level interning.
    pub projection: Box<[PlaceElem]>,
}

impl From<LocalId> for Place {
    /// Builds a bare-local place with an empty projection chain.
    fn from(local: LocalId) -> Self {
        Self {
            local,
            projection: Box::new([]),
        }
    }
}

/// Closed projection vocabulary.
///
/// This enum has exactly six variants in source-declaration order.
/// The bridge raises a diagnostic if a rustc `PlaceElem` outside this
/// set appears.
///
/// Structural invariants documented at this data-shape layer:
///
/// - I-Deref-first: if `place.projection[i]` is `Deref`, then
///   `i == 0`. Compound chains like `Field.Deref` cannot occur in
///   the accepted input.
/// - I-Downcast-followed-by-Field: if `place.projection[i]` is
///   `Downcast(_)`, then `i < projection.len() - 1` and
///   `projection[i + 1]` is `Field(_, _)`.
///
/// Enforcement is intentionally deferred to P1a-VAL-01
/// (regseq-model-83), which also checks the type-narrowing rules
/// documented in this module.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(tag = "kind", content = "data")]
pub enum PlaceElem {
    /// Pointer load: `*head` or `*projected_value`.
    ///
    /// Subject to the I-Deref-first invariant; enforcement lands in
    /// P1a-VAL-01 (regseq-model-83).
    Deref,

    /// Field projection.
    ///
    /// The `FieldIdx` indexes into the projected type's field list,
    /// dispatched by predecessor `Ty`. The inline `TyId` is the
    /// post-narrow field type, stored redundantly with what the
    /// layout would yield for cheap O(1) narrowing during the
    /// projection walk.
    Field(FieldIdx, TyId),

    /// Array or slice index by a runtime-computed value held in a
    /// separate local.
    ///
    /// The `LocalId` payload is the head of a separate
    /// `Place::from(local)` that produces the index value. `Index`
    /// carries a `LocalId`, not an `Operand`, so `Place` has no
    /// circular dependency on stage-6 `Operand`.
    Index(LocalId),

    /// Constant offset into a fixed-length array or slice.
    ///
    /// Generated by slice and array patterns. The `from_end` form is
    /// valid only for slices in accepted input; validation is
    /// deferred to P1a-VAL-01 (regseq-model-83).
    ConstantIndex {
        /// Element offset.
        offset: u64,
        /// Minimum source pattern length.
        min_length: u64,
        /// Whether the offset is counted from the runtime slice end.
        from_end: bool,
    },

    /// Sub-slice projection.
    ///
    /// Array bases use `from_end: false`; slice bases use
    /// `from_end: true` in accepted input. Validation is deferred to
    /// P1a-VAL-01 (regseq-model-83).
    Subslice {
        /// Inclusive start offset.
        from: u64,
        /// End offset, interpreted by `from_end`.
        to: u64,
        /// Whether `to` is counted from the runtime slice end.
        from_end: bool,
    },

    /// Downcast to a specific enum variant.
    ///
    /// Selects the active variant for the next `Field` projection.
    /// Subject to the I-Downcast-followed-by-Field invariant;
    /// enforcement lands in P1a-VAL-01 (regseq-model-83). The
    /// `VariantIdx` is the source-order variant index; rustc's
    /// printing-only variant-name slot is dropped.
    Downcast(VariantIdx),
}

#[cfg(test)]
mod tests {
    use std::collections::{hash_map::DefaultHasher, HashSet};
    use std::hash::{Hash, Hasher};

    use super::{Place, PlaceElem};
    use crate::{FieldIdx, LocalId, TyId, VariantIdx};

    fn hash_value<T: Hash>(value: &T) -> u64 {
        let mut hasher = DefaultHasher::new();
        value.hash(&mut hasher);
        hasher.finish()
    }

    fn representative_place_elems() -> [PlaceElem; 6] {
        [
            PlaceElem::Deref,
            PlaceElem::Field(FieldIdx::from_u32(0), TyId::from_u32(7)),
            PlaceElem::Index(LocalId::from_u32(4)),
            PlaceElem::ConstantIndex {
                offset: 0,
                min_length: 4,
                from_end: false,
            },
            PlaceElem::Subslice {
                from: 0,
                to: 3,
                from_end: false,
            },
            PlaceElem::Downcast(VariantIdx::from_u32(2)),
        ]
    }

    #[test]
    fn bare_local_place_construction() {
        let place = Place {
            local: LocalId::ZERO,
            projection: Box::new([]),
        };

        assert_eq!(place.local, LocalId::ZERO);
        assert!(place.projection.is_empty());
    }

    #[test]
    fn place_from_local_constructs_bare_local() {
        let place = Place::from(LocalId::from_u32(3));
        let manual = Place {
            local: LocalId::from_u32(3),
            projection: Box::new([]),
        };

        assert_eq!(place, manual);
    }

    #[test]
    fn place_elem_deref_constructs() {
        let elem = PlaceElem::Deref;

        assert_eq!(elem.clone(), PlaceElem::Deref);
    }

    #[test]
    fn place_elem_field_constructs() {
        let elem = PlaceElem::Field(FieldIdx::from_u32(2), TyId::from_u32(7));

        assert!(matches!(
            elem,
            PlaceElem::Field(field, ty)
                if field == FieldIdx::from_u32(2) && ty == TyId::from_u32(7)
        ));
    }

    #[test]
    fn place_elem_index_constructs() {
        let elem = PlaceElem::Index(LocalId::from_u32(4));

        assert!(matches!(
            elem,
            PlaceElem::Index(local) if local == LocalId::from_u32(4)
        ));
    }

    #[test]
    fn place_elem_constant_index_from_start_constructs() {
        let elem = PlaceElem::ConstantIndex {
            offset: 0,
            min_length: 4,
            from_end: false,
        };

        assert!(matches!(
            elem,
            PlaceElem::ConstantIndex {
                offset: 0,
                min_length: 4,
                from_end: false
            }
        ));
    }

    #[test]
    fn place_elem_constant_index_from_end_constructs_and_is_distinct() {
        let from_start = PlaceElem::ConstantIndex {
            offset: 0,
            min_length: 4,
            from_end: false,
        };
        let from_end = PlaceElem::ConstantIndex {
            offset: 1,
            min_length: 4,
            from_end: true,
        };

        assert!(matches!(
            from_end,
            PlaceElem::ConstantIndex {
                offset: 1,
                min_length: 4,
                from_end: true
            }
        ));
        assert_ne!(from_start, from_end);
    }

    #[test]
    fn place_elem_subslice_from_start_constructs() {
        let elem = PlaceElem::Subslice {
            from: 0,
            to: 3,
            from_end: false,
        };

        assert!(matches!(
            elem,
            PlaceElem::Subslice {
                from: 0,
                to: 3,
                from_end: false
            }
        ));
    }

    #[test]
    fn place_elem_subslice_from_end_constructs_and_is_distinct() {
        let from_start = PlaceElem::Subslice {
            from: 0,
            to: 3,
            from_end: false,
        };
        let from_end = PlaceElem::Subslice {
            from: 1,
            to: 0,
            from_end: true,
        };

        assert!(matches!(
            from_end,
            PlaceElem::Subslice {
                from: 1,
                to: 0,
                from_end: true
            }
        ));
        assert_ne!(from_start, from_end);
    }

    #[test]
    fn place_elem_downcast_constructs() {
        let elem = PlaceElem::Downcast(VariantIdx::from_u32(2));

        assert!(matches!(
            elem,
            PlaceElem::Downcast(variant) if variant == VariantIdx::from_u32(2)
        ));
    }

    #[test]
    fn all_place_elem_variants_are_pairwise_distinct() {
        let variants = representative_place_elems();

        for (idx, left) in variants.iter().enumerate() {
            for right in variants.iter().skip(idx + 1) {
                assert_ne!(left, right);
            }
        }
    }

    #[test]
    fn place_with_non_trivial_projection_constructs() {
        let place = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([
                PlaceElem::Deref,
                PlaceElem::Field(FieldIdx::ZERO, TyId::from_u32(7)),
            ]),
        };

        assert_eq!(place.local, LocalId::from_u32(1));
        assert_eq!(place.projection[0], PlaceElem::Deref);
        assert_eq!(
            place.projection[1],
            PlaceElem::Field(FieldIdx::ZERO, TyId::from_u32(7))
        );
    }

    #[test]
    fn identical_places_are_equal_and_hash_equal() {
        let left = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Deref]),
        };
        let right = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Deref]),
        };

        assert_eq!(left, right);
        assert_eq!(hash_value(&left), hash_value(&right));
    }

    #[test]
    fn places_with_different_projection_are_not_equal() {
        let left = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Deref]),
        };
        let right = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Field(FieldIdx::ZERO, TyId::from_u32(7))]),
        };

        assert_ne!(left, right);
    }

    #[test]
    fn places_with_different_local_are_not_equal() {
        let left = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Deref]),
        };
        let right = Place {
            local: LocalId::from_u32(2),
            projection: Box::new([PlaceElem::Deref]),
        };

        assert_ne!(left, right);
    }

    #[test]
    fn place_hashset_round_trips_distinct_values_and_clone() {
        let first = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Deref]),
        };
        let second = Place {
            local: LocalId::from_u32(2),
            projection: Box::new([PlaceElem::Deref]),
        };
        let mut set = HashSet::new();

        set.insert(first.clone());
        set.insert(second);
        assert_eq!(set.len(), 2);
        set.insert(first);
        assert_eq!(set.len(), 2);
    }

    #[test]
    fn place_elem_hash_discriminates_variants() {
        let mut set = HashSet::new();

        for elem in representative_place_elems() {
            set.insert(elem);
        }

        assert_eq!(set.len(), 6);
    }

    #[test]
    fn independently_constructed_projection_slabs_compare_by_contents() {
        let left = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Deref]),
        };
        let right = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([PlaceElem::Deref]),
        };

        assert_eq!(left, right);
    }

    #[test]
    fn empty_projection_slab_clone_round_trips_equality() {
        let place = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([]),
        };

        assert_eq!(place.clone(), place);
    }

    #[test]
    fn serde_round_trips_bare_local_place() {
        let place = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([]),
        };
        let json = serde_json::to_string(&place).unwrap();
        let decoded: Place = serde_json::from_str(&json).unwrap();

        assert_eq!(decoded, place);
    }

    #[test]
    fn serde_round_trips_non_trivial_place() {
        let place = Place {
            local: LocalId::from_u32(1),
            projection: Box::new([
                PlaceElem::Deref,
                PlaceElem::Field(FieldIdx::ZERO, TyId::from_u32(7)),
            ]),
        };
        let json = serde_json::to_string(&place).unwrap();
        let decoded: Place = serde_json::from_str(&json).unwrap();

        assert_eq!(decoded, place);
    }

    #[test]
    fn serde_round_trips_each_place_elem_variant() {
        for elem in representative_place_elems() {
            let json = serde_json::to_string(&elem).unwrap();
            let decoded: PlaceElem = serde_json::from_str(&json).unwrap();

            assert_eq!(decoded, elem);
        }
    }

    #[test]
    fn field_projection_redundant_ty_id_participates_in_equality() {
        let left = PlaceElem::Field(FieldIdx::from_u32(2), TyId::from_u32(7));
        let right = PlaceElem::Field(FieldIdx::from_u32(2), TyId::from_u32(8));

        assert_ne!(left, right);
    }

    #[test]
    fn downcast_variant_idx_participates_in_equality() {
        let left = PlaceElem::Downcast(VariantIdx::ZERO);
        let right = PlaceElem::Downcast(VariantIdx::from_u32(1));

        assert_ne!(left, right);
    }
}
