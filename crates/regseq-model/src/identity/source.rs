//! Source location types for the RegseqModel.
//!
//! [`SourceLocation`] captures a file range (start + end) with an interned
//! file path. [`SourceOrigin`] distinguishes user-authored source from
//! compiler-generated nodes.

use serde::{Deserialize, Serialize};

use super::FileId;

/// A source location range with interned file path.
#[derive(Clone, Eq, PartialEq, Hash, Serialize, Deserialize)]
pub struct SourceLocation {
    /// Interned file path.
    pub file: FileId,
    /// 1-based start line.
    pub start_line: u32,
    /// 1-based start column.
    pub start_column: u32,
    /// 1-based end line.
    pub end_line: u32,
    /// 1-based end column.
    pub end_column: u32,
}

impl std::fmt::Debug for SourceLocation {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "SourceLocation {{ file: {:?}, {}:{}-{}:{} }}",
            self.file, self.start_line, self.start_column, self.end_line, self.end_column,
        )
    }
}

/// The origin of an IR node: user source or compiler-generated.
#[derive(Clone, Eq, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", content = "data")]
pub enum SourceOrigin {
    /// From the spec author's source code.
    Source(SourceLocation),
    /// Generated by the compiler with no corresponding source line.
    CompilerGenerated,
}

impl std::fmt::Debug for SourceOrigin {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Source(loc) => write!(f, "Source({:?})", loc),
            Self::CompilerGenerated => write!(f, "CompilerGenerated"),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::identity::SymbolInterner;

    fn make_location(interner: &mut SymbolInterner) -> SourceLocation {
        SourceLocation {
            file: interner.intern_file("src/driver.rs"),
            start_line: 10,
            start_column: 5,
            end_line: 15,
            end_column: 1,
        }
    }

    #[test]
    fn serde_round_trip_source_location() {
        let mut interner = SymbolInterner::new();
        let loc = make_location(&mut interner);
        let json = serde_json::to_string(&loc).unwrap();
        let back: SourceLocation = serde_json::from_str(&json).unwrap();
        assert_eq!(loc, back);
    }

    #[test]
    fn serde_round_trip_source_origin_source() {
        let mut interner = SymbolInterner::new();
        let origin = SourceOrigin::Source(make_location(&mut interner));
        let json = serde_json::to_string(&origin).unwrap();
        let back: SourceOrigin = serde_json::from_str(&json).unwrap();
        assert_eq!(origin, back);
    }

    #[test]
    fn serde_round_trip_source_origin_compiler_generated() {
        let origin = SourceOrigin::CompilerGenerated;
        let json = serde_json::to_string(&origin).unwrap();
        let back: SourceOrigin = serde_json::from_str(&json).unwrap();
        assert_eq!(origin, back);
    }

    #[test]
    fn source_origin_uses_adjacently_tagged_format() {
        let origin = SourceOrigin::CompilerGenerated;
        let json = serde_json::to_string(&origin).unwrap();
        // Adjacently tagged: {"kind":"CompilerGenerated"}
        assert!(json.contains("\"kind\""));
    }

    #[test]
    fn source_location_equality() {
        let mut interner = SymbolInterner::new();
        let a = make_location(&mut interner);
        let b = make_location(&mut interner);
        assert_eq!(a, b);
    }

    #[test]
    fn source_location_inequality_on_different_lines() {
        let mut interner = SymbolInterner::new();
        let a = make_location(&mut interner);
        let b = SourceLocation {
            start_line: 99,
            ..a.clone()
        };
        assert_ne!(a, b);
    }
}
