//! D1 type-name derivation (`02-architecture-decisions.md` D1).
//!
//! A pure naming layer used by the `Ty`->C spelling ([`super::types`]) and
//! the section 14 aggregate emitter ([`super::layout_emit`]). Aggregate
//! **type** names are *derived* -- `sanitize(DefPath.rendered)` plus a
//! `generic_suffix(ArgsKey)` -- so they are a pure function of the model
//! and byte-stable. Task-11 adds [`instance_symbol_base`], the parallel
//! linkage-aware derivation for an instance's (fn / static) C symbol:
//! `sanitize(rendered)` with **no** generic suffix for external linkage (an
//! ABI contract, stable across monomorphizations) and the same
//! `sanitize(rendered) + generic_suffix(args)` form as type names for
//! internal linkage (so distinct monomorphizations of one generic item get
//! distinct symbols). Const instances materialise at use sites and so have
//! no standalone symbol.
//!
//! Collisions are impossible in a well-formed model because `(DefPath,
//! ArgsKey)` is the nominal identity key; the `_clash_<n>` disambiguation
//! pass in [`super::NameTable`] is the safety net.

use regseq_model::{
    args_key_for_generic_args, GenericArgs, Instance, InstanceKind, Linkage, RegseqModel, Ty, TyId,
};

/// The result of resolving an entry symbol from a model
/// ([`entry_c_symbol`]): the resolution either succeeds, finds no matching
/// function instance, or finds more than one (an ambiguous suffix).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EntrySymbol {
    /// Exactly one function instance matched; the emitted C symbol.
    Resolved(String),
    /// No function instance's `emission_name` ends with the suffix.
    NotFound,
    /// More than one function instance matched (an ambiguous suffix); the
    /// matched emitted symbols, for a precise diagnostic.
    Ambiguous(Vec<String>),
}

/// Resolve the entry function's emitted C symbol by a rendered-`emission_name`
/// suffix (Change F). Finds the **function** instance whose rendered
/// `emission_name` ends with `rendered_suffix`, then applies [`sanitize`] to
/// produce the emitted C symbol -- the single source of truth for the symbol
/// convention, reused by the on-disk coverage pipeline (it mints the entry the
/// same way the in-crate `fn_cname` resolver does). Returns [`EntrySymbol`] so a
/// caller can distinguish a missing entry from an ambiguous one.
pub fn entry_c_symbol(model: &RegseqModel, rendered_suffix: &str) -> EntrySymbol {
    let mut matches: Vec<String> = model
        .instances
        .iter()
        .filter(|inst| matches!(inst.kind, InstanceKind::Function(_)))
        .filter_map(|inst| {
            let rendered = model.strings.resolve(inst.emission_name);
            rendered
                .ends_with(rendered_suffix)
                .then(|| sanitize(rendered))
        })
        .collect();
    match matches.len() {
        0 => EntrySymbol::NotFound,
        1 => EntrySymbol::Resolved(matches.pop().expect("len == 1")),
        _ => EntrySymbol::Ambiguous(matches),
    }
}

/// Generate the `generic-c-backend.md` Doc-2 D3 entry shim `main.c` calling
/// the entry symbol `entry`: `int main(void) { <entry>(); return 0; }`.
///
/// The emitted generic-C translation unit is a library (it has no `main`),
/// and the entry lowers to a crate-qualified C symbol (`sanitize(emission_name)`,
/// resolved by [`entry_c_symbol`]), so a runnable binary needs this shim linked
/// alongside the TU. Single source of truth for the shim, reused by the
/// codegen-coverage runner (stages 4-5) and `cargo-regseq`'s `--emit bin`.
///
/// Unit-`void` form only; `{i,u}32` exit-code propagation is a deferred
/// feature (it lands with the first entry whose return carries a code).
pub fn generate_main_c(entry: &str) -> String {
    format!(
        "/* Generated by codegen-coverage-runner (Doc 2 D3 harness entry). */\n\
         extern void {entry}(void);\n\
         \n\
         int main(void) {{\n\
         \x20\x20\x20\x20{entry}();\n\
         \x20\x20\x20\x20return 0;\n\
         }}\n"
    )
}

/// Sanitize a rendered path into a C identifier body per D1: collapse
/// `::` to a single `_`, then map every remaining non-`[A-Za-z0-9_]`
/// byte to `_`. Total and deterministic.
pub(crate) fn sanitize(s: &str) -> String {
    s.replace("::", "_")
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

/// The D1 `generic_suffix(ArgsKey)`: empty for a non-generic item
/// (`args` empty), otherwise `__<hex>` of the canonical `ArgsKey` (the
/// same key the interner uses, so it is post-mono-unique and
/// build-stable).
fn generic_suffix(model: &RegseqModel, args: &GenericArgs) -> String {
    if args.is_empty() {
        String::new()
    } else {
        let key = args_key_for_generic_args(model, args);
        format!("__{:x}", key.0)
    }
}

/// The derived base name (pre-`_clash_<n>`) for an aggregate `ty`.
///
/// `Struct` / `Enum` / `Union` / `Closure` derive from the owning item's
/// `DefPath.rendered` + the generic suffix; tuples derive a stable
/// `tuple_<hash>` from their field `TyId`s (fields are then `_0`, `_1`,
/// ...). Panics if `ty` is not an aggregate -- callers only reach this
/// for discovered aggregate nodes.
pub(crate) fn aggregate_base_name(model: &RegseqModel, ty: TyId) -> String {
    match &model.types[ty] {
        Ty::Struct { item, args, .. }
        | Ty::Enum { item, args, .. }
        | Ty::Union { item, args, .. } => {
            let rendered = model.strings.resolve(model.items[*item].def_path.rendered);
            format!("{}{}", sanitize(rendered), generic_suffix(model, args))
        }
        Ty::Closure(item, args) => {
            // The parallel capture-struct name (D1 #3): same item + args.
            let rendered = model.strings.resolve(model.items[*item].def_path.rendered);
            format!("{}{}", sanitize(rendered), generic_suffix(model, args))
        }
        Ty::Tuple { fields, .. } => tuple_base_name(fields),
        other => panic!("aggregate_base_name on non-aggregate Ty: {other:?}"),
    }
}

/// The pre-clash C symbol base for a (fn / static) `instance` (task-11
/// Change A), linkage-aware. The base is `sanitize(emission_name)` for every
/// linkage; the difference is the generic suffix:
///
/// - **External** linkage (`NoMangle` -- which also covers `export_name` --
///   or `Foreign`) carries an ABI contract, so it gets **no generic suffix**:
///   the symbol is stable across every monomorphization (other translation
///   units / the harness link by that one name). Real external items are
///   non-generic (Rust rejects `#[no_mangle]` / `export_name` on generics),
///   so this matters only as a defensive guarantee.
/// - **Internal** linkage (`Default` / `Weak`) is translation-unit-local:
///   the symbol is `sanitize(emission_name) + generic_suffix(generic_args)`,
///   mirroring [`aggregate_base_name`]. The bridge mints one
///   `emission_name` (the generic-agnostic `DefPath.rendered`) per *item*,
///   so the `generic_suffix` of the *instance's* `generic_args` is what
///   distinguishes monomorphizations. The caller's `_clash_<n>` net
///   disambiguates any residual base collision.
///
/// Note: the base is `sanitize(emission_name)`, **not** the raw bytes. The
/// bridge mints `emission_name = DefPath.rendered` for *every* linkage
/// (including `Foreign` / `NoMangle`), e.g. `crate::{extern#0}::foo` -- not a
/// bare ABI identifier -- so the raw string is not valid C. The sibling
/// behavioral harness sanitises identically on both the emitted symbol and
/// the linked stub, so `sanitize` is the actual cross-TU contract; only a
/// generic *suffix* on an external symbol would break linkage, which is what
/// the linkage branch suppresses.
pub(crate) fn instance_symbol_base(model: &RegseqModel, instance: &Instance) -> String {
    let base = sanitize(model.strings.resolve(instance.emission_name));
    match model.items[instance.item].linkage {
        Linkage::NoMangle | Linkage::Foreign => base,
        Linkage::Default | Linkage::Weak => {
            format!("{base}{}", generic_suffix(model, &instance.generic_args))
        }
    }
}

/// A stable `tuple_<hash>` name from the field `TyId`s (FNV-1a over the
/// little-endian field indices). Deterministic within a model, hence
/// byte-stable across two emits of the same model.
fn tuple_base_name(fields: &[TyId]) -> String {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for f in fields {
        for b in f.as_u32().to_le_bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    format!("tuple_{h:016x}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sanitize_collapses_path_separator_then_maps_specials() {
        assert_eq!(sanitize("crate::mod::Foo"), "crate_mod_Foo");
        assert_eq!(sanitize("Foo<u32, [u8; 4]>"), "Foo_u32___u8__4__");
        assert_eq!(sanitize("already_ok_1"), "already_ok_1");
    }

    #[test]
    fn tuple_base_name_is_field_order_sensitive_and_stable() {
        let a = tuple_base_name(&[TyId::from_u32(1), TyId::from_u32(2)]);
        let b = tuple_base_name(&[TyId::from_u32(2), TyId::from_u32(1)]);
        assert_ne!(a, b);
        assert_eq!(a, tuple_base_name(&[TyId::from_u32(1), TyId::from_u32(2)]));
        assert!(a.starts_with("tuple_"));
    }
}
