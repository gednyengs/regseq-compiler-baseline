//! Linux-specific emission conventions.
//!
//! Houses Linux-kernel-flavored policy that is distinct from the
//! backend-neutral C AST in [`crate::c`]: SPDX banner, "Linux driver
//! artifact" framing, and similar kernel idioms.

use crate::c::CTopLevelItem;

/// Create a standard Regseq Linux-driver generated-file banner comment.
///
/// Emits the `SPDX-License-Identifier: GPL-2.0` header plus provenance
/// text. This is Linux-kernel policy; non-Linux C backends should not
/// use this banner.
pub fn generated_file_banner(filename: &str, driver_name: &str) -> CTopLevelItem {
    CTopLevelItem::BlockComment(vec![
        "SPDX-License-Identifier: GPL-2.0".to_string(),
        String::new(),
        format!("{filename} - Regseq-generated Linux driver artifact"),
        String::new(),
        "Generated by Regseq compiler. Do not edit.".to_string(),
        format!("Driver: {driver_name}"),
    ])
}
