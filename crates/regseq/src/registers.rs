/// Register support types and typed access wrappers for the Register Access surface.
///
/// These types form the compile-time facade for authored register operations.
/// Wrapper methods have placeholder bodies; the compiler replaces them with
/// backend-specific MMIO reads/writes during lowering.
use core::marker::PhantomData;
use core::ops::Add;

// ---------------------------------------------------------------------------
// RegisterOf trait and access control
// ---------------------------------------------------------------------------

/// Associates a register marker type with a register block and its access kind.
///
/// Per-register REG constants (RegisterId) are generated by register_block!
/// in each register's module, not carried on the trait.
pub trait RegisterOf<Block> {
    /// The access kind for this register (e.g. `ReadOnlyAccess`, `ReadWriteAccess`).
    type Access;
}

/// Marker trait for register width types (u8, u16, u32).
pub trait RegWidth:
    Copy
    + Clone
    + Default
    + core::ops::BitAnd<Output = Self>
    + core::ops::BitOr<Output = Self>
    + core::ops::Not<Output = Self>
{
}

impl RegWidth for u8 {}
impl RegWidth for u16 {}
impl RegWidth for u32 {}

/// Marker trait: the register supports read operations.
pub trait ReadAccess {}

/// Marker trait: the register supports write operations.
pub trait WriteAccess {}

/// Read-only access kind.
pub struct ReadOnlyAccess;
impl ReadAccess for ReadOnlyAccess {}

/// Write-only access kind.
pub struct WriteOnlyAccess;
impl WriteAccess for WriteOnlyAccess {}

/// Read-write access kind.
pub struct ReadWriteAccess;
impl ReadAccess for ReadWriteAccess {}
impl WriteAccess for ReadWriteAccess {}

// ---------------------------------------------------------------------------
// RegisterId
// ---------------------------------------------------------------------------

/// Identifies a full register for read/write operations (no field masking).
///
/// Each register module produces a `REG` constant of this type.
pub struct RegisterId<W, R> {
    _width: PhantomData<W>,
    _reg: PhantomData<R>,
}

// Manual impls to avoid requiring W: Copy/Clone and R: Copy/Clone bounds
// that the derive macro would impose.
impl<W, R> Copy for RegisterId<W, R> {}

impl<W, R> Clone for RegisterId<W, R> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<W, R> Default for RegisterId<W, R> {
    fn default() -> Self {
        Self::new()
    }
}

impl<W, R> RegisterId<W, R> {
    /// Create a new `RegisterId`.
    pub const fn new() -> Self {
        Self {
            _width: PhantomData,
            _reg: PhantomData,
        }
    }
}

// ---------------------------------------------------------------------------
// Field descriptor
// ---------------------------------------------------------------------------

/// Const-constructible field descriptor identifying a bitfield within a register.
///
/// `T` is the register width type (e.g. `u32`), `R` is the register marker type.
#[derive(Debug, Clone, Copy)]
pub struct Field<T, R> {
    pub mask: T,
    pub shift: T,
    _reg: PhantomData<R>,
}

impl<T, R> Field<T, R> {
    /// Create a new field descriptor with the given mask and shift.
    pub const fn new(mask: T, shift: T) -> Self {
        Self {
            mask,
            shift,
            _reg: PhantomData,
        }
    }
}

// ---------------------------------------------------------------------------
// Field value carrier
// ---------------------------------------------------------------------------

/// Const-constructible write-value carrier for register operations.
///
/// `T` is the register width type (e.g. `u32`), `R` is the register marker type.
/// Supports composition via `Add` so authored code like
/// `LCRH_REG::WLEN::WLEN_8 + LCRH_REG::FEN::SET` type-checks.
#[derive(Debug, Clone, Copy)]
pub struct FieldValue<T, R> {
    pub mask: T,
    pub value: T,
    _reg: PhantomData<R>,
}

impl<T, R> FieldValue<T, R> {
    /// Create a new field value with the given mask and value.
    pub const fn new(mask: T, value: T) -> Self {
        Self {
            mask,
            value,
            _reg: PhantomData,
        }
    }
}

/// Composition for `FieldValue`: combines two field values by ORing their masks and values.
impl<R> Add for FieldValue<u32, R> {
    type Output = Self;

    fn add(self, rhs: Self) -> Self {
        Self {
            mask: self.mask | rhs.mask,
            value: self.value | rhs.value,
            _reg: PhantomData,
        }
    }
}

